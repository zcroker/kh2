/* 0020f338 (12288 bytes): model draw routine, sibling of 00217d80 (same 0x300 work-block layout,
 * same header copy, luminance and VU0 vertex/normal transform). This variant reserves a 0x2800
 * work block, clips triangles against the screen with vclipw and builds GIF packets for prim
 * types 0..7 (four case pairs, each a hand-written VU0 loop that also kicks VIF/DMA).
 * Built as C (the switch on an s8 needs lb) with -fno-strict-aliasing => batch_w1661_nsa.c.
 * About 82% of the emitted instructions come from asm blocks (asm-only floor about 49%).
 * The asm text is the original's hand-written code, generated by scratch/w1661b/gen.py from
 * the template: gas macros (div rd,rs,rt / li / dli) are written as macros, as the original
 * programmer did (the expansions match gas exactly). What stays in asm and why:
 *  - the eight prim loops: pointer math and counters use trapping add/addi, s0-s2 are saved
 *    to and restored from the work block by the asm itself, branches use bne zero,rX and
 *    hand-filled delay slots (vwaitq, nop), so loop control cannot be C;
 *  - loop bodies whose first instruction sits in a gcc-filled delay slot of the original
 *    (0x40 path, normal loop): if that code were C, reorg would steal it into the slot.
 * C feeds the asm blocks through register-pinned variables; empty asm volatile("") lines are
 * scheduling barriers (0 instructions) that keep gcc's order between two asm blocks.
 */
